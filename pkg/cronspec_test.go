package crontools

import (
	"testing"
	"time"
)

const timeFormat = "2006-01-02T15:04"

func TestCronSchedule(t *testing.T) {
	schedules := [][]string{
		{"* * * * *", "2020-07-21T15:03", "2020-07-21T15:04", "2020-07-21T15:05"},
		{"* * * * *", "2019-12-31T23:59", "2020-01-01T00:00", "2020-01-01T00:01"},
		{"* * * * *", "2019-12-31T23:58", "2019-12-31T23:59", "2020-01-01T00:00"},
		{"*/10 * * * *", "2020-07-21T15:10", "2020-07-21T15:20", "2020-07-21T15:30"},
		{"*/10 * * * *", "2020-07-21T15:00", "2020-07-21T15:05", "2020-07-21T15:10"},
		{"10-15 * * * *", "2020-07-21T22:15", "2020-07-21T23:05", "2020-07-21T23:10"},
		{"10-15 * * * *", "2020-07-21T22:15", "2020-07-21T23:10", "2020-07-21T23:11"},
		{"10-15 * * * *", "2020-07-21T22:14", "2020-07-21T22:15", "2020-07-21T23:10"},
		{"10,40 * * * *", "2020-07-21T22:10", "2020-07-21T22:40", "2020-07-21T23:10"},
		{"10,40 * * * *", "2020-07-21T22:10", "2020-07-21T22:30", "2020-07-21T22:40"},
		{"10,40 * * * *", "2020-07-21T22:40", "2020-07-21T22:50", "2020-07-21T23:10"},
		{"10,40 * * * *", "2020-07-21T21:40", "2020-07-21T22:05", "2020-07-21T22:10"},
		{"30 2 * * *", "2020-07-20T02:30", "2020-07-21T02:30", "2020-07-22T02:30"},
		{"30 2 * * *", "2020-07-21T02:30", "2020-07-21T07:30", "2020-07-22T02:30"},
		{"30 2 * * *", "2020-07-20T02:30", "2020-07-21T01:30", "2020-07-21T02:30"},
		{"0 5 1-31/7 * *", "2020-07-01T05:00", "2020-07-08T05:00", "2020-07-15T05:00"},
		{"0 5 1-31/7 * *", "2020-07-01T05:00", "2020-07-03T05:00", "2020-07-08T05:00"},
		{"0 5 * * 1", "2020-06-29T05:00", "2020-07-06T05:00", "2020-07-13T05:00"},
		{"0 5 * * 1", "2020-06-29T05:00", "2020-07-04T05:00", "2020-07-06T05:00"},
	}

	for _, schedule := range schedules {
		spec, err := ParseCronTimeSpecification(schedule[0])
		if err != nil {
			t.Fatalf("cannot parse %s: %v", schedule[0], err)
		}

		tm, err := time.Parse(timeFormat, schedule[2])
		if err != nil {
			t.Fatalf("cannot parse date %s: %v", schedule[2], err)
		}

		if spec.PreviousDate(tm).Format(timeFormat) != schedule[1] {
			t.Fatalf("\"%s\": expected previous date of %s to be %s, got %s", schedule[0], schedule[2], schedule[1], spec.PreviousDate(tm).Format(timeFormat))
		}

		if spec.NextDate(tm).Format(timeFormat) != schedule[3] {
			t.Fatalf("\"%s\": expected next date of %s to be %s, got %s", schedule[0], schedule[2], schedule[3], spec.NextDate(tm).Format(timeFormat))
		}
	}
}
